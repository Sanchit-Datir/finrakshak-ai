/** Borrowers of the demo bank. */

import type { Borrower } from '../../domain/schemas.js';
import type { SeedContext } from './context.js';

export type MakeBorrower = (
  id: string,
  entityId: string,
  name: string,
  nameOriginal: string,
  type: Borrower['type'],
  branchId: string,
  masked: string,
  createdDays: number,
) => Borrower;

export function borrowerFactory(ctx: SeedContext): MakeBorrower {
  const { ago, manager } = ctx;
  return (
    id: string,
    entityId: string,
    name: string,
    nameOriginal: string,
    type: Borrower['type'],
    branchId: string,
    masked: string,
    createdDays: number,
  ): Borrower => ({
    id,
    entityId,
    name,
    nameOriginal,
    type,
    branchId,
    relationshipManager: manager,
    status: 'active',
    maskedIdentifier: masked,
    registrationNo: '',
    createdAt: ago(createdDays),
    updatedAt: ago(Math.max(1, Math.floor(createdDays / 6))),
  });
}

